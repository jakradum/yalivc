// Per-record layout of the LP data backup in the private GitHub repo, so git
// shows the history of every record:
//
//   <root>/records/<type>/<id>.json      one file per sanity_docs row: its `doc`,
//                                         keys sorted recursively, 2-space indent,
//                                         trailing newline (stable diffs)
//   <root>/records/_tables/<table>.json  the other tables: rows sorted by primary
//                                         key, same formatting
//   <root>/records/INDEX.md              type | name | file, to find a record by name
//
// A deleted row is a removed file. Pure functions only (no I/O): used by the
// scheduled run (run.js), the Coordinator's edit tool (edit.js) and the
// one-time seed (scripts/seed-record-history.mjs).
import { BACKUP_TABLES } from './export.js';
import { gitBlobSha } from './github.js';

export const RECORDS_DIR = 'records';
export const TABLES_DIR = '_tables';
export const INDEX_FILE = 'INDEX.md';
const SAFE_SEGMENT = /^[A-Za-z0-9_-][A-Za-z0-9_.-]*$/;

// Objects get their keys sorted (recursively); arrays keep their order.
export function sortKeys(v) {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).sort()) out[k] = sortKeys(v[k]);
    return out;
  }
  return v;
}

export const stableJson = (v) => `${JSON.stringify(sortKeys(v), null, 2)}\n`;

function segment(s, what) {
  if (typeof s !== 'string' || !SAFE_SEGMENT.test(s) || s.length > 200) throw new Error(`unsafe ${what} for a record path: ${JSON.stringify(String(s).slice(0, 40))}`);
  return s;
}

// Path relative to records/.
export const recordPath = (type, id) => `${segment(type, 'type')}/${segment(id, 'id')}.json`;
export const tablePath = (table) => `${TABLES_DIR}/${segment(table, 'table')}.json`;
export const isRecordFile = (rel) => !rel.startsWith(`${TABLES_DIR}/`) && rel !== INDEX_FILE && rel.endsWith('.json') && rel.includes('/');
export const typeOfPath = (rel) => rel.split('/')[0];

const cmp = (a, b) => {
  if (typeof a === 'number' && typeof b === 'number') return a - b;
  const x = String(a ?? '');
  const y = String(b ?? '');
  return x < y ? -1 : x > y ? 1 : 0;
};

export function tableJson(table, rows) {
  const pk = BACKUP_TABLES[table];
  if (!pk) throw new Error(`${table} is not a backup table`);
  return stableJson([...rows].sort((a, b) => cmp(a[pk], b[pk])));
}

// ── INDEX.md ─────────────────────────────────────────────────────────────────
// A readable name per record, never an email: types keyed by email get the id.
const ID_ONLY = new Set(['portalUser', 'newsletterSubscriber']);
const NAME_FIELDS = ['name', 'title', 'companyName', 'investeeName', 'fundName', 'label', 'subject'];
const EMAILISH = /@|%40/;

function clean(s) {
  const t = String(s ?? '').replace(/[\r\n|]+/g, ' ').replace(/\s+/g, ' ').trim();
  return t.length > 80 ? `${t.slice(0, 79)}…` : t;
}

export function recordLabel(doc, byId = new Map()) {
  if (!doc || typeof doc !== 'object') return '';
  const t = doc._type;
  const nameOf = (ref) => {
    const d = ref && byId.get(ref._ref);
    return d ? recordLabel(d, byId) : '';
  };
  let label = '';
  if (ID_ONLY.has(t)) label = doc._id;
  else if (t === 'lpInvestment') label = nameOf(doc.company);
  else if (t === 'lpCompanyQuarterUpdate') label = [nameOf(doc.investment), doc.quarter, doc.fiscalYear].filter(Boolean).join(' ');
  else if (t === 'lpDownloadConsent') label = [doc.downloadType || 'download', doc.reportQuarter, String(doc.consentedAt || '').slice(0, 10)].filter(Boolean).join(' ');
  else {
    for (const f of NAME_FIELDS) {
      if (typeof doc[f] === 'string' && doc[f].trim()) { label = doc[f]; break; }
    }
  }
  label = clean(label);
  if (!label || EMAILISH.test(label)) label = doc._id || '';
  return label;
}

export function indexMarkdown(docs) {
  const byId = new Map(docs.map((d) => [d._id, d]));
  const rows = docs
    .map((d) => ({ type: d._type, name: recordLabel(d, byId), path: recordPath(d._type, d._id) }))
    .sort((a, b) => cmp(a.type, b.type) || cmp(a.name.toLowerCase(), b.name.toLowerCase()) || cmp(a.path, b.path));
  const lines = [
    '# LP records index',
    '',
    `${rows.length} records, one file each under \`lp-data-backups/records/<type>/<id>.json\`. Generated by the backup; do not edit by hand. Emails are never listed here (people are listed by id).`,
    '',
    'History of one record: `git log -p -- lp-data-backups/records/<type>/<id>.json`. Other tables: `_tables/<table>.json`.',
    '',
    '| type | name | file |',
    '|---|---|---|',
    ...rows.map((r) => `| ${r.type} | ${r.name.replace(/\\/g, '\\\\')} | [${r.path}](${r.path}) |`),
  ];
  return `${lines.join('\n')}\n`;
}

// ── the whole records/ folder ────────────────────────────────────────────────
// tables: { sanity_docs: rows, sanity_files: rows, ... } (missing tables absent).
// → Map(path relative to records/ → string)
export function buildRecordFiles(tables) {
  const files = new Map();
  const docs = [];
  for (const row of tables.sanity_docs || []) {
    const doc = row.doc;
    if (!doc || doc._id !== row.id || doc._type !== row.type) throw new Error(`sanity_docs row ${String(row.id).slice(0, 40)}: doc._id/_type do not match the row`);
    files.set(recordPath(row.type, row.id), stableJson(doc));
    docs.push(doc);
  }
  for (const [table, rows] of Object.entries(tables)) {
    if (table === 'sanity_docs' || !rows) continue;
    files.set(tablePath(table), tableJson(table, rows));
  }
  files.set(INDEX_FILE, indexMarkdown(docs));
  return files;
}

// desired: Map(rel → string); listing: Map(rel → { sha }) of what is in the repo
// under records/. → { write: [[rel, content, sha]], remove: [rel] }, sorted by path.
// Only record files are ever removed: a missing table (not yet migrated) or the
// INDEX are left alone.
export function diffRecordFiles(desired, listing) {
  const write = [];
  for (const [rel, content] of desired) {
    const sha = gitBlobSha(Buffer.from(content, 'utf8'));
    if (listing.get(rel)?.sha !== sha) write.push([rel, content, sha]);
  }
  const remove = [...listing.keys()].filter((rel) => isRecordFile(rel) && !desired.has(rel));
  write.sort((a, b) => cmp(a[0], b[0]));
  remove.sort(cmp);
  return { write, remove };
}

// What a set of changes means, for commit messages and results.
// → { records, byType: { type: n }, added, changed, removed, tables: [names], index }
export function summarize({ write, remove }, listing) {
  const byType = {};
  let added = 0;
  let changed = 0;
  const tables = [];
  let index = false;
  for (const [rel] of write) {
    if (rel === INDEX_FILE) { index = true; continue; }
    if (rel.startsWith(`${TABLES_DIR}/`)) { tables.push(rel.slice(TABLES_DIR.length + 1).replace(/\.json$/, '')); continue; }
    byType[typeOfPath(rel)] = (byType[typeOfPath(rel)] || 0) + 1;
    if (listing.has(rel)) changed++;
    else added++;
  }
  for (const rel of remove) byType[typeOfPath(rel)] = (byType[typeOfPath(rel)] || 0) + 1;
  return { records: added + changed + remove.length, byType, added, changed, removed: remove.length, tables, index };
}

// "portal changes: 3 records (lpDownloadConsent 2, domainPrivilege 1)" + a body.
export function portalChangesMessage(sum, { newFiles = 0 } = {}) {
  const types = Object.entries(sum.byType).sort((a, b) => b[1] - a[1] || cmp(a[0], b[0])).map(([t, n]) => `${t} ${n}`).join(', ');
  const subject = `portal changes: ${sum.records} record${sum.records === 1 ? '' : 's'}${types ? ` (${types})` : ''}`;
  const body = [
    `added ${sum.added}, changed ${sum.changed}, removed ${sum.removed}`,
    sum.tables.length ? `tables: ${sum.tables.join(', ')}` : null,
    newFiles ? `new bucket files: ${newFiles}` : null,
  ].filter(Boolean);
  return `${subject}\n\n${body.join('\n')}`;
}
